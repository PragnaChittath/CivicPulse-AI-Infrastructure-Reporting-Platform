export function getTranslation(key: string, langCode: string): string {
  if (UI_TRANSLATIONS[langCode] && UI_TRANSLATIONS[langCode][key]) {
    return UI_TRANSLATIONS[langCode][key];
  }
  // Fallback to Hindi if regional script not directly mapped, or English
  if (langCode !== 'en' && UI_TRANSLATIONS['hi'] && UI_TRANSLATIONS['hi'][key]) {
    return UI_TRANSLATIONS['hi'][key];
  }
  return UI_TRANSLATIONS['en']?.[key] || key;
}
